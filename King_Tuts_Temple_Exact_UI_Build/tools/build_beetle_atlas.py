#!/usr/bin/env python3
"""Pack the user's 54 transparent beetle PNGs into shared PNG atlas pages.
Requires Pillow for rebuilding assets only. The game itself needs no Python.
Usage: python3 tools/build_beetle_atlas.py /path/to/beetle_animated_win.zip
"""
from pathlib import Path
from PIL import Image
import argparse, hashlib, io, json, math, re, zipfile
ROOT=Path(__file__).resolve().parents[1]
SIZE=384
PADDING=2
STEP=SIZE+2*PADDING
COLUMNS=5
PER_PAGE=25

def build(archive):
    output=ROOT/'assets/animations/beetle'
    output.mkdir(parents=True,exist_ok=True)
    with zipfile.ZipFile(archive) as z:
        names=sorted((n for n in z.namelist() if re.fullmatch(r'anim_\d+\.png',Path(n).name)),key=lambda n:int(re.search(r'(\d+)\.png',n).group(1)))
        if len(names)!=54:
            raise ValueError(f'Expected 54 beetle frames; found {len(names)}')
        images=[Image.open(io.BytesIO(z.read(n))).convert('RGBA') for n in names]
        if any(im.size!=(1024,1024) for im in images):
            raise ValueError('Expected all source frames to be 1024 x 1024')
        bounds=[im.getchannel('A').getbbox() for im in images]
        if any(b is None for b in bounds):raise ValueError('Empty animation frame')
        left=min(b[0] for b in bounds);top=min(b[1] for b in bounds)
        right=max(b[2] for b in bounds);bottom=max(b[3] for b in bounds)
        # Use ONE common square crop, never independent frame trimming.
        # This retains the authored motion and avoids frame-to-frame jitter.
        side=math.ceil((max(right-left,bottom-top)+24)/8)*8
        x=math.floor((left+right-side)/2);y=math.floor((top+bottom-side)/2)
        crop=(x,y,x+side,y+side)
        frames=[im.crop(crop).resize((SIZE,SIZE),Image.Resampling.LANCZOS) for im in images]
        pages=[];mapping=[]
        for start in range(0,len(frames),PER_PAGE):
            group=frames[start:start+PER_PAGE];cols=min(COLUMNS,len(group));rows=math.ceil(len(group)/cols)
            page=Image.new('RGBA',(cols*STEP,rows*STEP),(0,0,0,0))
            path=f'assets/animations/beetle/page-{len(pages)}.png'
            for j,im in enumerate(group):
                fx=(j%cols)*STEP+PADDING;fy=(j//cols)*STEP+PADDING
                # Direct paste keeps original alpha; do not alpha-mask twice.
                page.paste(im,(fx,fy))
                mapping.append({'page':len(pages),'x':fx,'y':fy,'w':SIZE,'h':SIZE,'source':Path(names[start+j]).name})
            page.save(ROOT/path,optimize=True)
            pages.append({'image':path,'width':page.width,'height':page.height})
        frames[0].save(ROOT/'assets/symbols/scatter.png',optimize=True)
        data={'version':1,'fps':30,'loop':False,'finish':'hold-last-frame','frameCount':len(frames),'frameSize':SIZE,'crop':list(crop),'pages':pages,'frames':mapping}
        (output/'atlas.json').write_text(json.dumps(data,indent=2)+'\n')
        (ROOT/'beetle-data.js').write_text('/* Generated by tools/build_beetle_atlas.py; 30 fps is a playback choice, not source metadata. */\nwindow.KEMET_BEETLE_DATA='+json.dumps(data,separators=(',',':'))+';\n')
        provenance={'sourceArchive':Path(archive).name,'archiveSha256':hashlib.sha256(Path(archive).read_bytes()).hexdigest(),'sourceSize':[1024,1024],'commonCrop':list(crop),'fpsNote':'Source contains PNGs only; playback set to 30 fps (1.8 seconds).','frames':[{'name':Path(n).name,'sha256':hashlib.sha256(z.read(n)).hexdigest()} for n in names]}
        (output/'SOURCE_MANIFEST.json').write_text(json.dumps(provenance,indent=2)+'\n')
        print(f'Packed {len(frames)} frames on {len(pages)} PNG pages; crop={crop}; fps=30')
        for p in pages:print(p['image'],(ROOT/p['image']).stat().st_size,'bytes',p['width'],p['height'])

if __name__=='__main__':
    parser=argparse.ArgumentParser(description=__doc__);parser.add_argument('archive',type=Path);args=parser.parse_args();build(args.archive)
